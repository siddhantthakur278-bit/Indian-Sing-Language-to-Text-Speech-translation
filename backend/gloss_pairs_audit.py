"""Reproducibly report conflicting records in the gloss-pair CSV."""

import argparse
import csv
from collections import defaultdict
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_CSV_PATH = PROJECT_ROOT / "data" / "gloss_pairs.csv"
REQUIRED_FIELDS = (
    "gloss_sequence",
    "english_sentence",
    "hindi_translation",
    "marathi_translation",
    "is_emergency",
)
TRANSLATION_FIELDS = (
    "english_sentence",
    "hindi_translation",
    "marathi_translation",
)


def audit_gloss_pairs(csv_path: Path = DEFAULT_CSV_PATH) -> str:
    """Return a stable Markdown report of duplicate-sequence disagreements."""
    grouped: dict[str, list[tuple[int, dict[str, str]]]] = defaultdict(list)
    with csv_path.open(encoding="utf-8-sig", newline="") as file:
        reader = csv.DictReader(file)
        if tuple(reader.fieldnames or ()) != REQUIRED_FIELDS:
            raise ValueError(
                f"Expected CSV fields in order: {', '.join(REQUIRED_FIELDS)}"
            )
        for line_number, row in enumerate(reader, start=2):
            if None in row or any(row.get(field) is None for field in REQUIRED_FIELDS):
                raise ValueError(f"Malformed CSV row at line {line_number}")
            sequence = row["gloss_sequence"].strip()
            grouped[sequence].append((line_number, row))

    duplicates = [
        (sequence, rows)
        for sequence, rows in sorted(grouped.items())
        if len(rows) > 1
    ]
    translation_conflicts = [
        (sequence, rows, field)
        for sequence, rows in duplicates
        for field in TRANSLATION_FIELDS
        if len({row[field].strip() for _, row in rows}) > 1
    ]
    emergency_conflicts = [
        (sequence, rows)
        for sequence, rows in duplicates
        if len({row["is_emergency"].strip().lower() for _, row in rows}) > 1
    ]

    report_lines = [
        "# Gloss-pair conflict audit",
        "",
        "Generated by `python -m backend.gloss_pairs_audit`.",
        "String differences are flagged for human review; this report does not",
        "determine whether translations or emergency labels are semantically correct.",
        "",
        f"- CSV rows: {sum(len(rows) for rows in grouped.values())}",
        f"- Repeated gloss sequences: {len(duplicates)}",
        f"- Conflicting translation fields: {len(translation_conflicts)}",
        f"- Conflicting emergency labels: {len(emergency_conflicts)}",
        "",
        "## Translation field disagreements",
        "",
    ]
    if not translation_conflicts:
        report_lines.append("None.")
    for sequence, rows, field in translation_conflicts:
        report_lines.extend(
            [
                f"### `{sequence}` — `{field}`",
                "",
                "| CSV line | Value |",
                "|---:|---|",
            ]
        )
        report_lines.extend(
            "| {} | {} |".format(
                line_number,
                row[field].strip().replace("|", "\\|"),
            )
            for line_number, row in rows
        )
        report_lines.append("")

    report_lines.extend(["## Emergency-label disagreements", ""])
    if not emergency_conflicts:
        report_lines.append("None.")
    for sequence, rows in emergency_conflicts:
        report_lines.extend(
            [
                f"### `{sequence}`",
                "",
                "| CSV line | Label | English sentence |",
                "|---:|---|---|",
            ]
        )
        report_lines.extend(
            "| {line} | {label} | {sentence} |".format(
                line=line_number,
                label=row["is_emergency"].strip().lower(),
                sentence=row["english_sentence"]
                .strip()
                .replace("|", "\\|"),
            )
            for line_number, row in rows
        )
        report_lines.append("")

    return "\n".join(report_lines).rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--csv",
        type=Path,
        default=DEFAULT_CSV_PATH,
        help="CSV to audit (default: data/gloss_pairs.csv)",
    )
    parser.add_argument(
        "--output",
        type=Path,
        help="write the report to this path instead of stdout",
    )
    args = parser.parse_args()
    report = audit_gloss_pairs(args.csv)
    if args.output:
        args.output.write_text(report, encoding="utf-8")
    else:
        print(report, end="")


if __name__ == "__main__":
    main()
